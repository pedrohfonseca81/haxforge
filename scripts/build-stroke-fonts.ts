// Builds src/smart/strokefonts.json from the single-stroke SVG fonts of the
// `hersheytext` package (Hershey fonts and Evil Mad Scientist's EMS fonts):
//
//   curl -sL https://registry.npmjs.org/hersheytext/-/hersheytext-2.0.0.tgz | tar xz
//   bun scripts/build-stroke-fonts.ts package/svg_fonts
//
// Glyphs are stored as polylines in the letreiro's glyph space: y down,
// baseline at 0, capitals 8 tall, x from the glyph origin; w = advance.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { douglasPeucker, pathToPolylines } from "../src/smart/svg";

// ASCII, the accented letters of Portuguese and Spanish, and a few symbols.
const CHARS = new Set([..."ÀÁÂÃÄÇÈÉÊËÌÍÎÏÑÒÓÔÕÖÙÚÛÜàáâãäçèéêëìíîïñòóôõöùúûü°ºª«»–—¡¿·"]);
for (let c = 32; c < 127; c++) CHARS.add(String.fromCharCode(c));
// Glyph space units (capitals are 8): invisible at any letter size.
const SIMPLIFY = 0.035;

const FONTS: [file: string, id: string, name: string][] = [
  ["HersheySans1", "hershey-sans", "Hershey Sans"],
  ["HersheySansMed", "hershey-sans-med", "Hershey Sans Médio"],
  ["HersheySerifMed", "hershey-serif", "Hershey Serif"],
  ["HersheySerifMedItalic", "hershey-serif-italic", "Hershey Serif Itálico"],
  ["HersheySerifBold", "hershey-serif-bold", "Hershey Serif Negrito"],
  ["HersheyScript1", "hershey-script", "Hershey Script"],
  ["HersheyScriptMed", "hershey-script-med", "Hershey Script Médio"],
  ["HersheyGothEnglish", "hershey-gothic", "Gótica"],
  ["EMSAllure", "ems-allure", "Allure (manuscrita)"],
  ["EMSElfin", "ems-elfin", "Elfin"],
  ["EMSFelix", "ems-felix", "Felix"],
  ["EMSNixish", "ems-nixish", "Nixish"],
  ["EMSOsmotron", "ems-osmotron", "Osmotron"],
  ["EMSReadability", "ems-readability", "Readability"],
  ["EMSTech", "ems-tech", "Tech"],
];

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun scripts/build-stroke-fonts.ts <svg_fonts dir>");
const decode = (s: string) =>
  s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16))).replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d))).replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
const r2 = (n: number) => Math.round(n * 100) / 100 + 0;

const out: Record<string, { name: string; glyphs: Record<string, { w: number; p: number[][] }> }> = {};
const notices: string[] = [];
for (const [file, id, name] of FONTS) {
  const svg = readFileSync(join(dir, `${file}.svg`), "utf8");
  notices.push(`## ${name} (${file})\n\n${svg.match(/<metadata>([\s\S]*?)<\/metadata>/)?.[1].trim() ?? ""}\n`);
  const defaultAdv = Number(svg.match(/<font [^>]*horiz-adv-x="([\d.]+)"/)?.[1] ?? 378);
  const raw = new Map<string, { w: number; lines: [number, number][][] }>();
  for (const m of svg.matchAll(/<glyph\s([^>]*?)\/?>/g)) {
    const attr = (k: string) => m[1].match(new RegExp(`\\b${k}="([^"]*)"`))?.[1];
    const ch = attr("unicode");
    if (ch === undefined) continue;
    const d = attr("d");
    raw.set(decode(ch), { w: Number(attr("horiz-adv-x") ?? defaultAdv), lines: d ? pathToPolylines(d) : [] });
  }
  // Capital height from the H (y up in SVG fonts).
  const capOf = (ch: string) => Math.max(...(raw.get(ch)?.lines.flat().map(([, y]) => y) ?? [0]));
  const cap = capOf("H") || capOf("I") || 700;
  const k = 8 / cap;
  const glyphs: Record<string, { w: number; p: number[][] }> = {};
  for (const [ch, g] of raw) {
    if (!CHARS.has(ch)) continue;
    const lines = g.lines.map((l) => douglasPeucker(l.map(([x, y]) => [x * k, -y * k] as [number, number]), SIMPLIFY));
    glyphs[ch] = { w: r2(g.w * k), p: lines.filter((l) => l.length > 1).map((l) => l.flatMap(([x, y]) => [r2(x), r2(y)])) };
  }
  out[id] = { name, glyphs };
}
writeFileSync(join(import.meta.dir, "../src/smart/strokefonts.json"), JSON.stringify(out));
writeFileSync(
  join(import.meta.dir, "../src/smart/STROKE_FONTS.md"),
  `# Single-stroke fonts\n\nGenerated by \`scripts/build-stroke-fonts.ts\` from the SVG fonts in the [hersheytext](https://github.com/techninja/hersheytextjs) package (MIT). The Hershey fonts were originally created by Dr. A. V. Hershey while working at the U. S. National Bureau of Standards; the format of the font data was originally created by James Hurt, Cognition, Inc. The EMS fonts by Evil Mad Scientist Laboratories are licensed under the SIL Open Font License (https://scripts.sil.org/OFL). Each font's own notice follows.\n\n${notices.join("\n")}`,
);
