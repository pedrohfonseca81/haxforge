// "Haxforge Sans": a stroke font made of HaxBall's own primitives. Round
// parts are curved segments (arcs), so an O costs 4 vertexes and 4 segments
// and still looks smooth at any size.
//
// Glyph space: screen axes (y down), baseline at y = 0, capitals 8 tall
// (y = -8), most letters 4 wide. A stroke is a list of points; the optional
// third number is the curve (degrees) of the segment that ends at that point,
// positive bulging to the left of the travel direction on screen.

export type StrokePt = [number, number] | [number, number, number];
export interface Glyph {
  w: number;
  s: StrokePt[][];
}

