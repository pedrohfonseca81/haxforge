function compose(base: Glyph, accent: StrokePt[][]): Glyph {
  // Accents are drawn for a 4-wide letter; center them on this one.
  const dx = base.w / 2 - 2;
  return { w: base.w, s: [...base.s, ...accent.map((st) => st.map((p) => [p[0] + dx, ...p.slice(1)] as StrokePt))] };
}

const GLYPHS: Record<string, Glyph> = { ...BASE };
for (const [ch, [base, accent]] of Object.entries(COMPOSED)) GLYPHS[ch] = compose(BASE[base], ACCENTS[accent]);
GLYPHS["Ç"] = { w: 4, s: [C, [[2, 0], [2, 0.8], [1.2, 1.8]]] };

// The glyph for a character (letters are drawn as capitals), or null.
export function glyph(ch: string): Glyph | null {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? null;
}

export const CAP_HEIGHT = 8;
export const SUPPORTED = Object.keys(GLYPHS).filter((c) => c !== " ").join("");
